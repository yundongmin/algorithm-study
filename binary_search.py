import sys

# 1. 입력 받기 및 오름차순 정렬
# n: 숫자의 개수 (예:8)
# m: 찾고자 하는 목표 숫자 (예: 32)
n, m = map(int, input().split())
a=list(map(int, input().split()))

# 이분 탐색의 전제 조건: 데이터가 반드시 "정렬"되어있어야 합니다.
a.sort()

# 2. 이분 탐색을 위한 양 끝 포인터 설정
# lt: 탐색 범위의 맨 왼쪽 인덱스 (0)
# rt: 탐색 범위의 맨 오른쪽 인덱스 (n-1)

lt=0
rt=n-1

# 3. 범위를 반씩 쪼개며 목표값 m 탐색
while lt <= rt:
    # 현재 탐색 범위의 정중앙 인덱스 계산
    mid = (lt+rt)//2

    # [경우1] 중앙값이 찾아려는 숫자 m과 딱 맞는 경우
    if a[mid] == m:
        # 문제에서 1번째부터 세는 번호를 요구하므로 1을 더해 출력\
        print(mid + 1)
        break # 정답을 찾았으므로 루프 탈출
    # [경우2] 중앙값이 m보다 큰 경우
    # -> m은 중앙값보다 왼쪽에 있으므로 오른쪽 절반을 버립니다.
    elif a[mid] > m:
        rt = mid -1

    # [경우3] 중앙값이 m보다 작은 경우
    # -> m은 중앙값보다 오른쪽에 있으므로 왼쪽 절반을 버립니다.
    else:
        lt=mid + 1










        