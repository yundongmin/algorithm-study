import sys

# 1. 승객수 N과 보트 최대 하중 M 입력 받기
n,m = map(int, input().split())
weights = list(map(int, input().split()))

# 2. 몸무게 오름차순 정렬
# 정렬 후 맨 앞은 가장 가벼운 사람, 맨 뒤는 가장 무거운 사람이 됩니다.

weights.sort()

#3. 양끝 포인터 및 보트 수 변수 초기화

lt=0        # 가장 가벼운 사람을 가리키는 포인터
rt=n-1      # 가장 무거운 사람을 가리키는 포인터
cnt=0       # 필요한 구명보트의 총 개수

# 4. 투 포인터로 승객 짝짓기 진행
while lt <=rt:
    # 마지막 한 사람만 남아있는 경우 (lt와 rt가 만났을 때)
    if lt == rt:
        cnt += 1    # 혼자 타고 탈출
        break

    # 가장 가벼운 사람 + 가장 무거운 사람의 무게가 한도 M이하인 경우
    if weights[lt] + weights[rt] <= m:
        cnt += 1    # 보트 1대에 2명 탑승
        lt += 1     # 가벼운 사람 처리 완료(오른쪽으로 한칸)
        rt -= 1     # 무거운 사람 처리 완료(왼쪽으로 한 칸)

    else: 
        # 가장 가벼운 사람 + 가장 무거운 사람의 무게가 한도 M이하인 경우
        cnt += 1    # 가장 무거운 사람 혼자 보트 1대 탑승
        rt -= 1     # 무거운 사람만 처리 완료(왼쪽으로 한 칸)
# 5. 필요한 최소 구명보트 개수 출력
print(cnt)